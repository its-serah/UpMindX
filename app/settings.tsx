import React, { useState } from 'react';
import { View, Text, StyleSheet, TextInput, Pressable, Alert, ScrollView } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import * as Haptics from 'expo-haptics';
import { configManager, setupMistralApiKey } from '@/lib/config';
import { initializeMistral } from '@/lib/mistral-api';
import { IconSymbol } from '@/components/ui/icon-symbol';
import { LoadingSpinner } from '@/components/ui/loading-states';
import { Colors, Spacing, BorderRadius } from '@/constants/theme';
import { useColorScheme } from '@/hooks/use-color-scheme';

export default function SettingsScreen() {
  const colorScheme = useColorScheme();
  const colors = Colors[colorScheme ?? 'light'];
  
  const [apiKey, setApiKey] = useState('');
  const [isConfigured, setIsConfigured] = useState(configManager.isMistralEnabled());
  const [isTesting, setIsTesting] = useState(false);
  const [validationError, setValidationError] = useState('');

  const validateApiKey = (key: string): boolean => {
    // Basic validation for Mistral API key format
    const trimmedKey = key.trim();
    if (!trimmedKey) {
      setValidationError('API key is required');
      return false;
    }
    if (trimmedKey.length < 10) {
      setValidationError('API key appears to be too short');
      return false;
    }
    if (!trimmedKey.startsWith('sk-') && !trimmedKey.includes('mistral')) {
      setValidationError('Please check your API key format');
      return false;
    }
    setValidationError('');
    return true;
  };

  const handleSaveApiKey = async () => {
    if (!validateApiKey(apiKey)) {
      return;
    }

    Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light);
    setIsTesting(true);

    try {
      const success = setupMistralApiKey(apiKey.trim());
      
      if (success) {
        initializeMistral(apiKey.trim());
        setIsConfigured(true);
        setApiKey(''); // Clear input for security
        setValidationError('');
        
        Alert.alert(
          'Success! 🎉',
          'Mistral AI is now configured. You\'ll get smarter questions based on video content!',
          [{ text: 'Great!', style: 'default' }]
        );
      } else {
        setValidationError('Invalid API key format. Please check and try again.');
      }
    } catch (error) {
      setValidationError('Failed to configure Mistral AI. Please try again.');
    } finally {
      setIsTesting(false);
    }
  };

  const handleDisableAI = () => {
    Alert.alert(
      'Disable AI Questions?',
      'This will switch back to basic questions. You can re-enable anytime.',
      [
        { text: 'Cancel', style: 'cancel' },
        {
          text: 'Disable',
          style: 'destructive',
          onPress: () => {
            configManager.setMistralApiKey('');
            setIsConfigured(false);
            Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success);
          }
        }
      ]
    );
  };

  return (
    <SafeAreaView style={styles.container}>
      <ScrollView style={styles.scrollView}>
        <View style={styles.content}>
          <Text style={styles.title}>Settings</Text>
          
          {/* AI Configuration Section */}
          <View style={styles.section}>
            <View style={styles.sectionHeader}>
              <IconSymbol name="brain" size={24} color="#6366F1" />
              <Text style={styles.sectionTitle}>AI-Powered Questions</Text>
            </View>
            
            <Text style={styles.sectionDescription}>
              Get contextual, intelligent questions generated by Mistral AI based on video content.
            </Text>

            {isConfigured ? (
              <View style={styles.configuredContainer}>
                <View style={styles.statusContainer}>
                  <IconSymbol name="checkmark.circle.fill" size={20} color="#22C55E" />
                  <Text style={styles.configuredText}>AI Questions Enabled</Text>
                </View>
                
                <Text style={styles.configuredDescription}>
                  You&apos;re getting smart, contextual questions powered by AI!
                </Text>
                
                <Pressable 
                  style={styles.disableButton}
                  onPress={handleDisableAI}
                >
                  <Text style={styles.disableButtonText}>Disable AI</Text>
                </Pressable>
              </View>
            ) : (
              <View style={styles.configurationContainer}>
                <Text style={styles.inputLabel}>Mistral API Key</Text>
                <TextInput
                  style={[
                    styles.apiKeyInput,
                    validationError && styles.apiKeyInputError,
                    { borderColor: validationError ? colors.error : colors.border }
                  ]}
                  placeholder="Enter your Mistral API key..."
                  value={apiKey}
                  onChangeText={(text) => {
                    setApiKey(text);
                    if (validationError) {
                      setValidationError('');
                    }
                  }}
                  secureTextEntry
                  autoCapitalize="none"
                  autoCorrect={false}
                  editable={!isTesting}
                />
                
                {validationError ? (
                  <Text style={[styles.errorText, { color: colors.error }]}>
                    {validationError}
                  </Text>
                ) : null}
                
                <Pressable
                  style={[
                    styles.saveButton, 
                    { backgroundColor: colors.primary },
                    (!apiKey.trim() || isTesting || validationError) && [styles.saveButtonDisabled, { backgroundColor: colors.textTertiary }]
                  ]}
                  onPress={handleSaveApiKey}
                  disabled={!apiKey.trim() || isTesting || !!validationError}
                >
                  {isTesting ? (
                    <View style={styles.saveButtonContent}>
                      <LoadingSpinner size="small" color="white" />
                      <Text style={styles.saveButtonText}>Configuring...</Text>
                    </View>
                  ) : (
                    <Text style={styles.saveButtonText}>Save API Key</Text>
                  )}
                </Pressable>
                
                <Text style={styles.helpText}>
                  💡 Get your free API key from mistral.ai
                  {"\n"}🔒 Your key is stored locally and securely
                </Text>
              </View>
            )}
          </View>
          
          {/* App Info Section */}
          <View style={styles.section}>
            <View style={styles.sectionHeader}>
              <IconSymbol name="info.circle" size={24} color="#8B5CF6" />
              <Text style={styles.sectionTitle}>App Information</Text>
            </View>
            
            <View style={styles.infoRow}>
              <Text style={styles.infoLabel}>Version</Text>
              <Text style={styles.infoValue}>1.0.0</Text>
            </View>
            
            <View style={styles.infoRow}>
              <Text style={styles.infoLabel}>Made with</Text>
              <Text style={styles.infoValue}>❤️ for growth-minded learners</Text>
            </View>
          </View>
        </View>
      </ScrollView>
    </SafeAreaView>
  );
}

